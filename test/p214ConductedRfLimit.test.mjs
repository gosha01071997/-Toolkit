import test from "node:test";
import assert from "node:assert/strict";
import { определить_нормативный_рисунок, получить_предельный_уровень } from "../src/calculations/p214ConductedRfLimit.mjs";
import { НОРМАТИВНЫЕ_КРИВЫЕ_21_4 } from "../src/data/limits/p214ConductedRfLimits.mjs";

const питание = "Цепь электропитания";
const жгут = "Межсоединительный жгут";
const частоты = [0.15, 1, 2, 30, 108, 152];
const наборы = [
  ["21-1 / B", "B", питание, "21-1", [73, 48.83, 40, 40, 50, 50]],
  ["21-1 / L", "L", питание, "21-1", [53, 28.83, 20, 20, 30, 30]],
  ["21-1 / M", "M", питание, "21-1", [53, 28.83, 20, 20, 30, 30]],
  ["21-1 / H", "H", питание, "21-1", [53, 28.83, 20, 20, 30, 30]],
  ["21-2 / B", "B", жгут, "21-2", [93, 68.83, 60, 50, 40, 40]],
  ["21-2 / L", "L", жгут, "21-2", [73, 48.83, 40, 30, 20, 20]],
  ["21-2 / M", "M", жгут, "21-2", [73, 48.83, 40, 30, 20, 20]],
  ["21-2 / H", "H", жгут, "21-2", [73, 48.83, 40, 30, 20, 20]],
  ["21-3 / P / питание", "P", питание, "21-3", [53, 28.83, 9, 9, 10, 10]],
  ["21-3 / P / жгут", "P", жгут, "21-3", [53, 28.83, 9, 9, 10, 10]],
  ["21-4 / Q", "Q", питание, "21-4", [53, 28.83, 20, 20, 20, 20]],
  ["21-5 / Q", "Q", жгут, "21-5", [63, 38.83, 30, 30, 20, 20]],
];

for (const [название, категория, объект, рисунок, ожидаемые] of наборы) {
  test(`21.4: контрольные частоты ${название}`, () => {
    частоты.forEach((частота, индекс) => {
      const результат = получить_предельный_уровень(частота, категория, объект);
      assert.equal(результат.рисунок, рисунок);
      assert.ok(Math.abs(результат.предельный_уровень_дбмка - ожидаемые[индекс]) < 0.005, `${частота}: ${результат.предельный_уровень_дбмка}`);
    });
  });
}

test("21.4: выбор рисунка не смешивает P и Q", () => {
  assert.deepEqual(определить_нормативный_рисунок("P", питание), { рисунок: "21-3", есть_нормативное_примечание: false });
  assert.deepEqual(определить_нормативный_рисунок("P", жгут), { рисунок: "21-3", есть_нормативное_примечание: false });
  assert.deepEqual(определить_нормативный_рисунок("Q", питание), { рисунок: "21-4", есть_нормативное_примечание: true });
  assert.deepEqual(определить_нормативный_рисунок("Q", жгут), { рисунок: "21-5", есть_нормативное_примечание: true });
});

test("21.4: Errata хранится как метаданные и не меняет кривые Q", () => {
  for (const рисунок of ["21-4", "21-5"]) assert.deepEqual(
    [НОРМАТИВНЫЕ_КРИВЫЕ_21_4[рисунок].исходная_категория, НОРМАТИВНЫЕ_КРИВЫЕ_21_4[рисунок].категория_в_errata_2016, НОРМАТИВНЫЕ_КРИВЫЕ_21_4[рисунок].есть_нормативное_расхождение],
    ["Q", "P", true],
  );
  assert.equal(НОРМАТИВНЫЕ_КРИВЫЕ_21_4["21-3"].формула_до_2_мгц.смещение, 28.83);
});

test("21.4: обязательные поля и рабочий диапазон проверяются", () => {
  assert.equal(получить_предельный_уровень(1, "", питание).ошибка, "Выберите категорию испытания.");
  assert.equal(получить_предельный_уровень(1, "B", "").ошибка, "Выберите объект измерения.");
  for (const частота of [0.149999, 152.000001, Number.NaN]) assert.equal(получить_предельный_уровень(частота, "B", питание).ошибка, "Частота находится вне диапазона испытания 21.4 (0,15–152 МГц).");
});

const около = [1.999999, 2, 2.000001, 29.999999, 30, 30.000001, 107.999999, 108, 108.000001];
const проверкиИзломов = [
  ["B", питание, [39.99929144721302, 40, 40, 40, 40, 50, 50, 50, 50]],
  ["B", жгут, [59.99929144721302, 60, 60, 60, 50, 50, 50, 40, 40]],
  ["P", питание, [19.999291447213018, 9, 9, 9, 9, 20, 20, 10, 10]],
  ["Q", питание, [19.999291447213018, 20, 20, 20, 20, 30, 30, 20, 20]],
  ["Q", жгут, [29.999291447213018, 30, 30, 30, 30, 30, 30, 20, 20]],
];

for (const [категория, объект, ожидаемые] of проверкиИзломов) test(`21.4: точки около изломов ${категория} / ${объект}`, () => {
  около.forEach((частота, индекс) => assert.ok(Math.abs(получить_предельный_уровень(частота, категория, объект).предельный_уровень_дбмка - ожидаемые[индекс]) < 1e-6, `${частота}`));
});
