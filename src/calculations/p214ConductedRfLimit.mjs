import {
  МАКСИМАЛЬНАЯ_ЧАСТОТА_21_4_МГЦ,
  МИНИМАЛЬНАЯ_ЧАСТОТА_21_4_МГЦ,
  НОРМАТИВНЫЕ_КРИВЫЕ_21_4,
  ОБЪЕКТЫ_ИЗМЕРЕНИЯ_21_4,
} from "../data/limits/p214ConductedRfLimits.mjs";

const КАТЕГОРИИ = ["B", "L", "M", "H", "P", "Q"];

export function определить_нормативный_рисунок(категория, тип_объекта) {
  const категорияНорм = String(категория || "").toUpperCase();
  if (!КАТЕГОРИИ.includes(категорияНорм)) return { ошибка: "Выберите категорию испытания." };
  if (!ОБЪЕКТЫ_ИЗМЕРЕНИЯ_21_4.includes(тип_объекта)) return { ошибка: "Выберите объект измерения." };
  let рисунок;
  if (["B", "L", "M", "H"].includes(категорияНорм)) рисунок = тип_объекта === "Цепь электропитания" ? "21-1" : "21-2";
  else if (категорияНорм === "P") рисунок = "21-3";
  else рисунок = тип_объекта === "Цепь электропитания" ? "21-4" : "21-5";
  return { рисунок, есть_нормативное_примечание: Boolean(НОРМАТИВНЫЕ_КРИВЫЕ_21_4[рисунок].есть_нормативное_расхождение) };
}

const форматЧисла = число => String(число).replace(".", ",");

export function получить_предельный_уровень(частота_мгц, категория, тип_объекта) {
  const выбор = определить_нормативный_рисунок(категория, тип_объекта);
  const частота = typeof частота_мгц === "number" ? частота_мгц : Number(частота_мгц);
  const основа = { частота_мгц: частота, категория: String(категория || "").toUpperCase(), тип_объекта };
  if (выбор.ошибка) return { ...основа, ошибка: выбор.ошибка };
  if (!Number.isFinite(частота) || частота < МИНИМАЛЬНАЯ_ЧАСТОТА_21_4_МГЦ || частота > МАКСИМАЛЬНАЯ_ЧАСТОТА_21_4_МГЦ) {
    return { ...основа, ...выбор, ошибка: "Частота находится вне диапазона испытания 21.4 (0,15–152 МГц)." };
  }

  const описание = НОРМАТИВНЫЕ_КРИВЫЕ_21_4[выбор.рисунок];
  const кривая = описание.категории
    ? описание.категории[основа.категория === "B" ? "B" : "L_M_H"]
    : описание;
  if (частота < 2) {
    const { наклон, смещение } = кривая.формула_до_2_мгц;
    return {
      ...основа, ...выбор,
      предельный_уровень_дбмка: наклон * Math.log10(частота) + смещение,
      способ_расчёта: "Логарифмическая формула",
      диапазон: "0,15–2 МГц",
      формула: `${форматЧисла(наклон).replace("-", "−")} × log10(частота) + ${форматЧисла(смещение)}`,
    };
  }

  // В точке вертикального перехода рассматриваются оба соседних участка;
  // минимальный предел реализует внутреннее консервативное правило Toolkit.
  const подходящие = кривая.участки.filter(([начало, конец]) => частота >= начало && частота <= конец);
  const выбранный = подходящие.reduce((строгий, участок) => !строгий || участок[2] < строгий[2] ? участок : строгий, null);
  return {
    ...основа, ...выбор,
    предельный_уровень_дбмка: выбранный[2],
    способ_расчёта: "Постоянный участок",
    диапазон: `${форматЧисла(выбранный[0])}–${форматЧисла(выбранный[1])} МГц`,
  };
}

export function построить_точки_кривой_21_4(категория, тип_объекта, число_точек = 160) {
  const точки = Array.from({ length: число_точек }, (_, индекс) => {
    const частота = МИНИМАЛЬНАЯ_ЧАСТОТА_21_4_МГЦ * (МАКСИМАЛЬНАЯ_ЧАСТОТА_21_4_МГЦ / МИНИМАЛЬНАЯ_ЧАСТОТА_21_4_МГЦ) ** (индекс / (число_точек - 1));
    return получить_предельный_уровень(частота, категория, тип_объекта);
  });
  for (const частота of [2, 30, 108]) {
    const слева = получить_предельный_уровень(частота - Number.EPSILON * частота, категория, тип_объекта);
    const вТочке = получить_предельный_уровень(частота, категория, тип_объекта);
    const справа = получить_предельный_уровень(частота + Number.EPSILON * частота, категория, тип_объекта);
    if (!слева.ошибка) точки.push(слева, вТочке, справа);
  }
  return точки.sort((a, b) => a.частота_мгц - b.частота_мгц);
}
